def normalize_lang(lang: str | None) -> str:
    code = str(lang or "").strip().lower().split("-")[0]
    return code if code in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE


def translations(lang: str | None) -> dict[str, str]:
    code = normalize_lang(lang)
    base = dict(TRANSLATIONS[DEFAULT_LANGUAGE])
    base.update(TRANSLATIONS.get(code, {}))
    return base


def t(key: str, lang: str | None = DEFAULT_LANGUAGE) -> str:
    return translations(lang).get(key, key)


def agent_language_instruction(lang: str | None) -> str:
    code = normalize_lang(lang)
    if code == "el":
        return ""
    name = SUPPORTED_LANGUAGES[code]
    return (
        f"UI language preference: {name} ({code}). "
        f"Respond in {name} by default, or match the language the user writes in."
    )
